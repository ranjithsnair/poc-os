/*
 * Framebuffer text console: renders an 8x8 bitmap font onto the linear
 * framebuffer Limine sets up before jumping to the kernel, with its own
 * cursor tracking and line-wrap/scroll -- this is what serial_print()/
 * serial_putc() used to do over COM1. Every glyph is drawn scaled up 2x
 * (16x16 on screen) since a typical boot video mode is far higher
 * resolution than an 8x8 cell would need, and tiny text is unreadable.
 *
 * Pixel format (bit depth, RGB shifts/sizes) comes from the
 * limine_framebuffer struct handed to fb_init() -- nothing here assumes
 * 32bpp/BGRX specifically, so it still works if Limine hands us a 16bpp
 * or 24bpp mode instead.
 */
