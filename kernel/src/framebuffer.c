static uint8_t *fb_addr;
static uint64_t fb_width;
static uint64_t fb_height;
static uint64_t fb_pitch;
static uint32_t fb_bytes_per_pixel;

static uint8_t fb_red_size, fb_red_shift;
static uint8_t fb_green_size, fb_green_shift;
static uint8_t fb_blue_size, fb_blue_shift;

static uint32_t cols, rows;
static uint32_t cursor_col, cursor_row;

/* Packs 8-bit RGB into whatever bit layout this framebuffer's mode
 * actually uses, shifting each component down to fit its mask size (e.g.
 * an 8-bit 0xFF red component becomes a 5-bit 0x1F on a 16bpp/565 mode)
 * before placing it at its mask shift. */
static uint32_t fb_pack_color(uint8_t r, uint8_t g, uint8_t b) {
    uint32_t rv = (uint32_t)(r >> (8 - fb_red_size)) << fb_red_shift;
    uint32_t gv = (uint32_t)(g >> (8 - fb_green_size)) << fb_green_shift;
    uint32_t bv = (uint32_t)(b >> (8 - fb_blue_size)) << fb_blue_shift;
    return rv | gv | bv;
}

static void fb_put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    uint8_t *pixel = fb_addr + (uint64_t)y * fb_pitch + (uint64_t)x * fb_bytes_per_pixel;
    for (uint32_t i = 0; i < fb_bytes_per_pixel; i++) {
        pixel[i] = (uint8_t)(color >> (8 * i));
    }
}

static void fb_draw_glyph(uint32_t col, uint32_t row, char c, uint32_t fg, uint32_t bg) {
    uint32_t px0 = col * CHAR_W;
    uint32_t py0 = row * CHAR_H;
    const uint8_t *glyph = font8x8_basic[(uint8_t)c < 0x80 ? (uint8_t)c : 0];
    for (uint32_t gy = 0; gy < GLYPH_H; gy++) {
        uint8_t bits = glyph[gy];
        for (uint32_t gx = 0; gx < GLYPH_W; gx++) {
            uint32_t color = (bits & (1 << gx)) ? fg : bg;
            for (uint32_t sy = 0; sy < SCALE; sy++) {
                for (uint32_t sx = 0; sx < SCALE; sx++) {
                    fb_put_pixel(px0 + gx * SCALE + sx, py0 + gy * SCALE + sy, color);
                }
            }
        }
    }
}

/* Moves every row of pixels up by one character cell (memmove, since
 * source and destination overlap) and blanks the newly exposed row at
 * the bottom -- black is 0 regardless of pixel format, so a plain memset
 * works without needing fb_pack_color(). */
static void fb_scroll(void) {
    uint64_t row_bytes = (uint64_t)CHAR_H * fb_pitch;
    uint64_t total_bytes = fb_pitch * fb_height;
    memmove(fb_addr, fb_addr + row_bytes, (size_t)(total_bytes - row_bytes));
    memset(fb_addr + (total_bytes - row_bytes), 0, (size_t)row_bytes);
}

static void fb_newline(void) {
    cursor_col = 0;
    if (cursor_row + 1 >= rows) {
        fb_scroll();
    } else {
        cursor_row++;
    }
}

void fb_init(struct limine_framebuffer *fb) {
    fb_addr = (uint8_t *)fb->address;
    fb_width = fb->width;
    fb_height = fb->height;
    fb_pitch = fb->pitch;
    fb_bytes_per_pixel = (fb->bpp + 7) / 8;

    fb_red_size = fb->red_mask_size;
    fb_red_shift = fb->red_mask_shift;
    fb_green_size = fb->green_mask_size;
    fb_green_shift = fb->green_mask_shift;
    fb_blue_size = fb->blue_mask_size;
    fb_blue_shift = fb->blue_mask_shift;

    cols = (uint32_t)(fb_width / CHAR_W);
    rows = (uint32_t)(fb_height / CHAR_H);
    cursor_col = 0;
    cursor_row = 0;

    memset(fb_addr, 0, (size_t)(fb_pitch * fb_height));
}

void fb_putc(char c) {
    uint32_t fg = fb_pack_color(0xFF, 0xFF, 0xFF);
    uint32_t bg = fb_pack_color(0x00, 0x00, 0x00);

    if (c == '\n') {
        fb_newline();
        return;
    }
    if (c == '\b') {
        if (cursor_col > 0) {
            cursor_col--;
            fb_draw_glyph(cursor_col, cursor_row, ' ', fg, bg);
        }
        return;
    }
    if (c == '\t') {
        cursor_col = (cursor_col + 8) & ~7u;
        if (cursor_col >= cols) {
            fb_newline();
        }
        return;
    }

    fb_draw_glyph(cursor_col, cursor_row, c, fg, bg);
    cursor_col++;
    if (cursor_col >= cols) {
        fb_newline();
    }
}

void fb_print(const char *str) {
    for (size_t i = 0; str[i] != '\0'; i++) {
        fb_putc(str[i]);
    }
}

void fb_print_dec(uint64_t v) {
    char buf[21]; /* enough digits for the largest possible uint64_t, plus '\0' */
    int i = 20;
    buf[i] = '\0';
    if (v == 0) {
        buf[--i] = '0';
    }
    while (v > 0) {
        buf[--i] = (char)('0' + (v % 10));
        v /= 10;
    }
    fb_print(&buf[i]);
}
